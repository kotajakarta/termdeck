"""Opens TermDeck as a desktop app window, like the Android app (used by run.sh).

    python scripts/desktop_app.py open --port 9095 [--wait]   open the app window
    python scripts/desktop_app.py install --port 9095         (WSL) install the Start Menu shortcut + tray

Under WSL the window is Chrome/Edge in app mode on the Windows side, managed by a tray icon
(scripts/windows/termdeck-tray.ps1) that is copied to %LOCALAPPDATA%\\TermDeck together with a Start
Menu shortcut. On native Linux a Chromium-family browser is opened with --app, otherwise the default
browser. Run it with the virtualenv's interpreter.
"""

import argparse
import json
import os
import platform
import shutil
import socket
import struct
import subprocess
import sys
import time
import webbrowser
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from app.config import data_dir  # noqa: E402

TRAY_SCRIPT = ROOT / "scripts" / "windows" / "termdeck-tray.ps1"
ICON_PNGS = [ROOT / "frontend" / "public" / "favicon-32.png", ROOT / "frontend" / "public" / "apple-touch-icon.png"]
LINUX_BROWSERS = [
    "chromium",
    "chromium-browser",
    "google-chrome",
    "google-chrome-stable",
    "brave-browser",
    "microsoft-edge",
    "microsoft-edge-stable",
]
APP_DIR_NAME = "TermDeck"
SHORTCUT_NAME = "TermDeck.lnk"


# ---- pure helpers (unit tested) ----------------------------------------------


def is_wsl(release: str | None = None) -> bool:
    return "microsoft" in (release if release is not None else platform.release()).lower()


def png_size(png: bytes) -> tuple[int, int]:
    """Width and height from the IHDR chunk of a PNG file."""
    if png[:8] != b"\x89PNG\r\n\x1a\n" or png[12:16] != b"IHDR":
        raise ValueError("bukan file PNG")
    width, height = struct.unpack(">II", png[16:24])
    return width, height


def build_ico(pngs: list[bytes]) -> bytes:
    """Windows .ico holding the PNG images as-is (supported since Windows Vista)."""
    header = struct.pack("<HHH", 0, 1, len(pngs))
    offset = len(header) + 16 * len(pngs)
    entries = b""
    for png in pngs:
        width, height = png_size(png)
        # 0 means 256 pixels in the one-byte size fields.
        entries += struct.pack("<BBBBHHII", width % 256, height % 256, 0, 0, 1, 32, len(png), offset)
        offset += len(png)
    return header + entries + b"".join(pngs)


def render_launcher_vbs(ps1_windows_path: str) -> str:
    """VBScript starting the tray hidden: a shortcut to powershell.exe would flash a console window."""
    command = (
        'powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File ""' + ps1_windows_path + '""'
    )
    return (
        "' TermDeck launcher (generated by scripts/desktop_app.py)\r\n"
        'CreateObject("WScript.Shell").Run "' + command + '", 0, False\r\n'
    )


def render_config(distro: str, repo: str, port: int) -> str:
    return json.dumps({"distro": distro, "repo": repo, "port": port}, indent=2) + "\n"


def find_linux_browser(which: Callable[[str], str | None]) -> str | None:
    for name in LINUX_BROWSERS:
        path = which(name)
        if path:
            return path
    return None


def linux_app_command(browser: str, url: str, profile_dir: Path) -> list[str]:
    # A dedicated profile gives TermDeck its own window/taskbar entry, separate from normal browsing.
    return [browser, f"--app={url}", f"--user-data-dir={profile_dir}", "--no-first-run", "--no-default-browser-check"]


def wait_for_port(port: int, timeout: float, host: str = "127.0.0.1") -> bool:
    deadline = time.monotonic() + timeout
    while True:
        try:
            with socket.create_connection((host, port), timeout=0.5):
                return True
        except OSError:
            if time.monotonic() >= deadline:
                return False
            time.sleep(0.1)


# ---- WSL / Windows side ------------------------------------------------------


def _windows_cwd() -> str:
    # Windows programs started from a Linux folder print "UNC paths are not supported" warnings.
    return "/mnt/c" if os.path.isdir("/mnt/c") else "/"


def windows_env(name: str) -> str:
    out = subprocess.run(
        ["cmd.exe", "/d", "/c", f"echo %{name}%"], capture_output=True, text=True, cwd=_windows_cwd(), check=True
    )
    value = out.stdout.strip()
    if not value or value == f"%{name}%":
        raise RuntimeError(f"variabel Windows {name} tidak ditemukan")
    return value


def wslpath(flag: str, path: str) -> str:
    return subprocess.run(["wslpath", flag, path], capture_output=True, text=True, check=True).stdout.strip()


def write_if_changed(path: Path, data: bytes) -> bool:
    if path.exists() and path.read_bytes() == data:
        return False
    path.write_bytes(data)
    return True


def _ps_quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def create_shortcut(lnk: str, target: str, arguments: str, icon: str, workdir: str) -> None:
    script = (
        f"$s = (New-Object -ComObject WScript.Shell).CreateShortcut({_ps_quote(lnk)}); "
        f"$s.TargetPath = {_ps_quote(target)}; "
        f"$s.Arguments = {_ps_quote(arguments)}; "
        f"$s.IconLocation = {_ps_quote(icon + ',0')}; "
        f"$s.WorkingDirectory = {_ps_quote(workdir)}; "
        "$s.Description = 'TermDeck - terminal SSH multi-server'; "
        "$s.Save()"
    )
    subprocess.run(
        ["powershell.exe", "-NoProfile", "-NonInteractive", "-Command", script],
        cwd=_windows_cwd(),
        check=True,
        stdout=subprocess.DEVNULL,
    )


def install_windows(port: int) -> Path:
    """Copy the tray + launcher to %LOCALAPPDATA%\\TermDeck and add the Start Menu shortcut.

    Returns the Linux path of launcher.vbs. Idempotent: files are only rewritten when they change.
    """
    distro = os.environ.get("WSL_DISTRO_NAME", "")
    if not distro:
        raise RuntimeError("WSL_DISTRO_NAME tidak ada; jalankan dari shell WSL")
    local_win = windows_env("LOCALAPPDATA") + "\\" + APP_DIR_NAME
    local = Path(wslpath("-u", local_win))
    local.mkdir(parents=True, exist_ok=True)

    changed = False
    changed |= write_if_changed(local / "termdeck-tray.ps1", TRAY_SCRIPT.read_bytes())
    changed |= write_if_changed(local / "config.json", render_config(distro, str(ROOT), port).encode())
    changed |= write_if_changed(local / "termdeck.ico", build_ico([p.read_bytes() for p in ICON_PNGS]))
    vbs = local / "launcher.vbs"
    changed |= write_if_changed(vbs, render_launcher_vbs(local_win + "\\termdeck-tray.ps1").encode("ascii"))

    programs_win = windows_env("APPDATA") + "\\Microsoft\\Windows\\Start Menu\\Programs"
    lnk_win = programs_win + "\\" + SHORTCUT_NAME
    if changed or not Path(wslpath("-u", lnk_win)).exists():
        system_root = windows_env("SystemRoot")
        create_shortcut(
            lnk=lnk_win,
            target=system_root + "\\System32\\wscript.exe",
            arguments=f'"{local_win}\\launcher.vbs"',
            icon=local_win + "\\termdeck.ico",
            workdir=local_win,
        )
    return vbs


def open_windows(port: int) -> None:
    vbs = install_windows(port)
    # The tray makes sure the server answers, then opens or focuses the app window.
    subprocess.Popen(
        ["wscript.exe", wslpath("-w", str(vbs))],
        cwd=_windows_cwd(),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )


# ---- native Linux --------------------------------------------------------------


def open_linux(url: str) -> None:
    if not (os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY")):
        print("Tidak ada layar grafis; buka sendiri " + url)
        return
    browser = find_linux_browser(shutil.which)
    if browser is None:
        webbrowser.open(url)
        return
    profile = data_dir() / "app-browser"
    subprocess.Popen(
        linux_app_command(browser, url, profile),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="TermDeck sebagai aplikasi desktop")
    parser.add_argument("command", choices=["open", "install"])
    parser.add_argument("--port", type=int, default=9095)
    parser.add_argument("--wait", action="store_true", help="tunggu server siap (maks. 30 detik) sebelum membuka")
    args = parser.parse_args(argv)

    try:
        if args.command == "install":
            if not is_wsl():
                print("install hanya diperlukan di WSL (shortcut Start Menu + ikon tray Windows).")
                return 1
            install_windows(args.port)
            return 0
        if args.wait and not wait_for_port(args.port, timeout=30):
            print(f"TermDeck belum siap di port {args.port}; jendela aplikasi tidak dibuka.", file=sys.stderr)
            return 1
        if is_wsl():
            open_windows(args.port)
        else:
            open_linux(f"http://localhost:{args.port}/")
    except (OSError, RuntimeError, subprocess.CalledProcessError) as exc:
        print(f"Mode aplikasi gagal dibuka: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
